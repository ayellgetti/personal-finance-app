type Row = readonly [name: string, unit: string];

const slug = (value: string): string =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const category = (name: string, rows: readonly Row[]): ProcurementItem[] =>
  rows.map(([item, unit]) => ({
    id: `${slug(name)}-${slug(item)}`,
    name: item,
    unit,
    category: name,
  }));

